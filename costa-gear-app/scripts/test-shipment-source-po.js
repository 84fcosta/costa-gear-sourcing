const assert = require("assert");
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const read = p => fs.readFileSync(path.join(__dirname,"..",p),"utf8");
const ctx = {};
vm.runInNewContext(read("src/domain/shipmentSourcePO.js").replace(/export function/g,"function")+"\nthis.api={sourcePOOptions,shipmentHeaderUpdate}",ctx);
const {sourcePOOptions,shipmentHeaderUpdate}=ctx.api;
const orders=[{id:"a",po_ref:"PO0003",status:"Received"},{id:"b",status:"Ordered"},{id:"c",status:"Cancelled"},{id:"d",status:"Draft"},{id:"e",status:"Partially Received"},{id:"f",status:"Approved"}];
assert.equal(JSON.stringify(sourcePOOptions(orders,null).map(o=>o.id)),JSON.stringify(["b","e","f"]));
assert.equal(sourcePOOptions(orders,{purchase_order_id:"a"})[0].po_ref,"PO0003");
assert.ok(sourcePOOptions(orders,{purchase_order_id:"c"}).some(o=>o.id==="c"));
assert.ok(sourcePOOptions(orders,{purchase_order_id:"missing"}).some(o=>o.id==="missing" && o.po_ref.includes("Linked PO")));
assert.ok(!sourcePOOptions(orders,{purchase_order_id:null}).some(o=>o.id==="a"));
const form={purchaseOrderId:"",notes:"test",freightAmount:"1180.00"};
const payload=shipmentHeaderUpdate(form);
assert.ok(!("purchaseOrderId" in payload));
assert.equal(payload.notes,"test");
assert.equal(payload.freightAmount,"1180.00");
assert.ok("purchaseOrderId" in form);
const workspace=read("src/components/ShipmentAllocationWorkspace.js");
assert.match(workspace,/updateShipment\(selectedId,shipmentHeaderUpdate\(form\)\)/);
assert.match(workspace,/selected\?\.purchase_order_id/);
assert.match(workspace,/sourcePOOptions\(orders, selectedId \? selected : null\)/);
console.log("Shipment Source PO display and link preservation tests passed.");
